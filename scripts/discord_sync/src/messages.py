from __future__ import annotations

import re

_PLACEHOLDER = re.compile(r"\{\{([^}]+)\}\}")


def fill(template: str, values: dict[str, str]) -> str:
    """テンプレートの {{名前}} を値で置き換える

    対応する値が無い {{名前}} は空文字にする

    Args:
        template: {{名前}} を含む文字列
        values: 名前から値への対応

    Returns:
        置き換えた文字列
    """
    return _PLACEHOLDER.sub(lambda match: str(values.get(match.group(1), "")), template)


